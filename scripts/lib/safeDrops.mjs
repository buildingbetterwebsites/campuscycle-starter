// Makes a generated migration that removes collections safe to run (used by scripts/remove-example.mjs).
//
// Payload's `migrate:create` writes the removal of a collection as DROP TABLE ... CASCADE first, and then
// drops the same foreign keys (DROP CONSTRAINT) a second time. CASCADE has already removed them, so that
// second drop stops the migration with 'constraint "..." does not exist', on every database, a new one
// too. A course team ran into exactly this when it removed the example collections.
//
// safeDrops() changes only the up() part of the migration:
//   1. it first deletes the rows that go: the links to the removed collections in Payload's link tables
//      (the *_rels tables that keep a column), then the removed tables' own rows, link tables first;
//   2. every DROP TABLE, DROP CONSTRAINT, DROP INDEX, DROP COLUMN and DROP TYPE gets IF EXISTS, so a
//      drop that CASCADE already did is skipped instead of stopping the migration.
// The down() part (undoing the migration) stays exactly as Payload wrote it.

const MARK = '-- Rows first (added by npm run remove-example):'

/**
 * @param {string} source the migration file (.ts) as `migrate:create` wrote it
 * @returns {{ source: string, tables: string[], changed: boolean }} the safe file, and the tables it removes
 */
export function safeDrops(source) {
  const upStart = source.indexOf('export async function up(')
  const downStart = source.indexOf('export async function down(')
  if (upStart === -1 || downStart === -1 || downStart < upStart) {
    throw new Error('This file does not look like a migration: it has no up() followed by a down().')
  }
  let up = source.slice(upStart, downStart)
  const rest = source.slice(downStart)
  // Already made safe (the command ran twice): leave it as it is.
  if (up.includes(MARK)) return { source, tables: droppedTables(up), changed: false }

  const tables = droppedTables(up)
  const links = [...up.matchAll(/ALTER TABLE "([a-z0-9_]+_rels)" DROP COLUMN "([a-z0-9_]+)"/g)]
    .filter(([, table]) => !tables.includes(table))
    .map(([, table, column]) => `DELETE FROM "${table}" WHERE "${column}" IS NOT NULL;`)
  // Link tables before the tables they point at: the starter's database rules refuse to delete a topic
  // that a workshop still links to (src/lib/modelSchema.ts).
  const ordered = [...tables.filter((table) => table.endsWith('_rels')), ...tables.filter((table) => !table.endsWith('_rels'))]
  const deletes = [...links, ...ordered.map((table) => `DELETE FROM "${table}";`)]

  up = up
    .replace(/DROP TABLE "/g, 'DROP TABLE IF EXISTS "')
    .replace(/DROP CONSTRAINT "/g, 'DROP CONSTRAINT IF EXISTS "')
    .replace(/DROP INDEX "/g, 'DROP INDEX IF EXISTS "')
    .replace(/DROP COLUMN "/g, 'DROP COLUMN IF EXISTS "')
    .replace(/DROP TYPE "/g, 'DROP TYPE IF EXISTS "')
  if (deletes.length > 0) {
    const at = up.indexOf('sql`')
    if (at === -1) throw new Error('The migration has no sql`...` statement to add the row deletions to.')
    up = `${up.slice(0, at + 4)}\n  ${MARK}\n  ${deletes.join('\n  ')}\n${up.slice(at + 4)}`
  }
  const note = [
    '// Generated by `npm run migrate:create`, then made safe by `npm run remove-example`',
    '// (scripts/lib/safeDrops.mjs): up() first deletes the rows that go, and every DROP has IF EXISTS,',
    '// because DROP TABLE ... CASCADE already removes the foreign keys the generator drops again later.',
    '',
  ].join('\n')
  return { source: note + source.slice(0, upStart) + up + rest, tables, changed: true }
}

/** The tables up() drops, in the order it drops them. */
function droppedTables(up) {
  return [...up.matchAll(/DROP TABLE (?:IF EXISTS )?"([a-z0-9_]+)"/g)].map((match) => match[1])
}
