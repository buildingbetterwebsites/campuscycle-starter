// A rule for every site made from this starter: a page that reads the database reads it on every
// visit. Read from the source files themselves, because no page render can show it.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const root = fileURLToPath(new URL('../..', import.meta.url))
const read = (file: string) => readFileSync(path.join(root, file), 'utf8')

function pageFiles(folder: string, file = 'page.tsx'): string[] {
  return readdirSync(path.join(root, folder)).flatMap((name) => {
    const relative = path.join(folder, name)
    if (statSync(path.join(root, relative)).isDirectory()) return pageFiles(relative, file)
    return name === file ? [relative] : []
  })
}

// Does this source read the database? Yes when it calls getPayload, or imports a value (not only a
// type) from payload or the Payload config, or imports from a src/lib helper that itself reads the
// database. It does not see a database read hidden in a component or a package the page imports.
const DATA_IMPORT = /^import (?!type\b)[^;]*?from '(payload|@payload-config|@\/payload\.config)'/m

function readsTheDatabase(source: string): boolean {
  if (/\bgetPayload\b/.test(source) || DATA_IMPORT.test(source)) return true
  return [...source.matchAll(/^import (?!type\b)[^;]*?from '@\/lib\/([\w/-]+)'/gm)].some(([, name]) => {
    const file = ['.ts', '.tsx'].map((ext) => `src/lib/${name}${ext}`).find((candidate) => existsSync(path.join(root, candidate)))
    return file ? readsTheDatabase(read(file)) : false
  })
}

describe('the public pages read the database on every visit, never during the build', () => {
  it('knows which imports read the database', () => {
    expect(readsTheDatabase("import config from '@payload-config'")).toBe(true)
    expect(readsTheDatabase("import config from '@/payload.config'")).toBe(true)
    expect(readsTheDatabase("import { getPayload } from 'payload'")).toBe(true)
    expect(readsTheDatabase("import { findPage } from '@/lib/pages'")).toBe(true)
    expect(readsTheDatabase("import type { Page } from '@/payload-types'")).toBe(false)
    expect(readsTheDatabase("import type { Metadata } from 'payload'")).toBe(false)
    expect(readsTheDatabase("import { formatPrice } from '@/lib/format'")).toBe(false)
  })

  it("every page under src/app/(site) that reads the database says dynamic = 'force-dynamic'", () => {
    const pages = pageFiles('src/app/(site)').filter((file) => readsTheDatabase(read(file)))
    // The home page, the clinic list, the plain pages and Contact, at least.
    expect(pages.length).toBeGreaterThanOrEqual(4)
    for (const file of pages) {
      expect(read(file), file).toMatch(/^export const dynamic = 'force-dynamic'$/m)
    }
  })

  it("every route handler under src/app/api that reads the database says dynamic = 'force-dynamic'", () => {
    // Payload's own routes (src/app/(payload)) are generated by Payload and left as they are.
    const routes = pageFiles('src/app/api', 'route.ts').filter((file) => readsTheDatabase(read(file)))
    // The course check, at least.
    expect(routes).toContain(path.join('src/app/api/course-check/route.ts'))
    for (const file of routes) {
      expect(read(file), file).toMatch(/^export const dynamic = 'force-dynamic'$/m)
    }
  })
})
